def icon(name):
    text, outline = ART[name]
    rows = [r for r in text.strip("\n").splitlines()]
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        raise ValueError(f"{name}：16×16になっていない（{[len(r) for r in rows]}）")
    p = Pixel()
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            p.put(x, y, hexc(PALETTE[ch]))
    p.outline(outline)
    return p.icon()


NAMES = ("ancient_stone_helm", "ancient_stone_cuirass", "ancient_stone_greaves", "ancient_stone_sabatons",
         "ancient_stone_hood", "ancient_stone_robe", "ancient_stone_legwear", "ancient_stone_boots")


def save_all(repo):
    base = os.path.join(repo, "src/main/resources/assets/amemaru/textures/item")
    for n in NAMES:
        icon(n).save(os.path.join(base, n + ".png"))


if __name__ == "__main__":
    from PIL import Image
    out = sys.argv[1] if len(sys.argv) > 1 else "/tmp/armor_icons.png"
    s = Image.new("RGBA", (8 * 16 * 4 + 50, 8 * 16 * 2 + 30), (139, 139, 139, 255))
    for k, n in enumerate(NAMES):
        im = icon(n).big(8)
        s.alpha_composite(im, (10 + (k % 4) * (128 + 10), 10 + (k // 4) * (128 + 10)))
    s.save(out)
