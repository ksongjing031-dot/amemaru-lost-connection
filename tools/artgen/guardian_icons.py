def _c(k):
    return hexc(PAL[k])


def draw_greatsword():
    """核剣：白い石の刃（格子の溝）と、まん中の翠のすじ・左の青銅の背・斜めに断った先・根元の四角の輪の翠の核・長い握り。"""
    p = Pixel()
    p.diag_band(7, 14, lambda t: [_c("G"), _c("Z"), _c("q") if t % 2 else _c("f"), _c("z"), _c("Y")]
                + ([_c("U")] if t <= 12 else []), dx0=-2)
    for t in (9, 12):  # 格子の溝
        x, y = p.axis(t)
        p.put(x + 1, y, _c("y"))
        p.put(x + 3, y, _c("u"))
    x, y = p.axis(15)
    p.put(x - 2, y, _c("Z"))
    p.put(x - 1, y, _c("z"))
    for u in range(-3, 4):  # 四角の輪（ななめの棒）
        x, y = p.axis(5)
        p.put(x + u, y + u, _c("G") if abs(u) == 3 else _c("g"))
        p.put(x + u + 1, y + u, _c("h"))
    x, y = p.axis(5)
    p.put(x, y, _c("F"))
    p.put(x + 1, y, _c("q"))
    for t in (2, 3, 4):
        x, y = p.axis(t)
        p.put(x, y, _c("k") if t % 2 else _c("K"))
        p.put(x + 1, y, _c("K") if t % 2 else _c("k"))
    x, y = p.axis(3)
    p.put(x, y, _c("G"))
    x, y = p.axis(1)
    p.put(x, y, _c("Z"))
    p.put(x + 1, y, _c("y"))
    p.put(x, y + 1, _c("q"))
    return p


def draw_staff():
    """核杖：積んだ石の柄（白い布の握り）と、先の四角の青銅の輪・その中に浮かぶ翠の立方体。"""
    p = Pixel()
    for t in range(0, 10):
        x, y = p.axis(t)
        if t in (3, 4, 5):
            p.put(x, y, _c("W"))
            p.put(x + 1, y, _c("X"))
        else:
            p.put(x, y, _c("k") if t % 2 else _c("K"))
            p.put(x + 1, y, _c("x"))
    head = {}
    for k in range(0, 6):  # 四角の輪
        head[(10 + k, 0)] = "G"
        head[(10 + k, 5)] = "h"
        head[(10, k)] = "g"
        head[(15, k)] = "h"
    for (px, py) in ((10, 0), (15, 0), (10, 5), (15, 5)):
        head[(px, py)] = "Z"
    head.update({(12, 2): "F", (13, 2): "f", (12, 3): "q", (13, 3): "Q"})
    for (px, py), k in head.items():
        p.put(px, py, _c(k))
    x, y = p.axis(9)
    p.put(x, y, _c("g"))
    return p


def draw_bell_staff():
    """核鈴：積んだ石の柄（白い布の握り）と、先の青銅の横木から下がる段の石の鐘と翠の舌。"""
    p = Pixel()
    for t in range(0, 9):
        x, y = p.axis(t)
        if t in (3, 4, 5):
            p.put(x, y, _c("W"))
            p.put(x + 1, y, _c("X"))
        else:
            p.put(x, y, _c("k") if t % 2 else _c("K"))
            p.put(x + 1, y, _c("x"))
    head = {
        # 横木（青銅）と、両はしの石
        (9, 1): "Z", (10, 1): "G", (11, 1): "g", (12, 1): "G", (13, 1): "g", (14, 1): "G", (15, 1): "Z",
        (9, 2): "y", (15, 2): "y", (9, 3): "q", (15, 3): "q",
        # 鐘（段の石）
        (12, 2): "h", (11, 3): "z", (12, 3): "Z", (13, 3): "y",
        (10, 4): "z", (11, 4): "Z", (12, 4): "z", (13, 4): "y", (14, 4): "Y",
        (10, 5): "Y", (11, 5): "y", (12, 5): "y", (13, 5): "Y", (14, 5): "u",
        (12, 6): "F",
    }
    for (px, py), k in head.items():
        p.put(px, py, _c(k))
    x, y = p.axis(9)
    p.put(x, y, _c("g"))
    return p


DRAWN = {"guardian_greatsword": draw_greatsword, "guardian_staff": draw_staff, "guardian_bell_staff": draw_bell_staff}

