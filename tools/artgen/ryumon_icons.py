def _check(name, art):
    rows = art.strip("\n").splitlines()
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        raise ValueError(f"{name}：16×16になっていない（{[len(r) for r in rows]}）")
    for y, row in enumerate(rows):
        for ch in row:
            if ch != "." and ch not in PAL:
                raise ValueError(f"{name}：{y}行目の「{ch}」の色がない")
    return rows


def _from_art(name):
    p = Pixel()
    for y, row in enumerate(_check(name, ART[name])):
        for x, ch in enumerate(row):
            if ch != ".":
                p.put(x, y, hexc(PAL[ch]))
    return p


# ---------------------------------------------------------------- 武器（ななめの軸に沿って）

def _c(k):
    return hexc(PAL[k])


def draw_sword():
    """流紋の剣：青銅の刃（左上のふちが明るい）と、まん中の水の溝・翼の鍔とまん中の結晶・暗い革の握り・輪の柄頭。"""
    p = Pixel()
    p.diag_band(7, 13, lambda t: [_c("Z"), _c("f") if t % 2 else _c("q"), _c("y")], dx0=-1)
    x, y = p.axis(14)
    p.put(x - 1, y, _c("Z"))
    p.put(x, y, _c("z"))
    x, y = p.axis(15)
    p.put(x - 1, y, _c("Z"))
    for u in range(-3, 4):  # 鍔（ななめの棒）と、両はしの上がり
        x, y = p.axis(6)
        p.put(x + u, y + u, _c("z") if abs(u) < 3 else _c("Z"))
        p.put(x + u + 1, y + u, _c("Y"))
    x, y = p.axis(6)
    p.put(x, y, _c("f"))
    p.put(x + 1, y, _c("q"))
    for t in (3, 4, 5):  # 握り
        x, y = p.axis(t)
        p.put(x, y, _c("l") if t % 2 else _c("L"))
        p.put(x + 1, y, _c("L") if t % 2 else _c("l"))
    x, y = p.axis(1)  # 輪の柄頭と結晶
    p.put(x, y, _c("y"))
    p.put(x + 1, y, _c("Z"))
    p.put(x, y + 1, _c("u"))
    p.put(x + 1, y - 1, _c("Y"))
    p.put(x + 2, y - 1, _c("f"))
    return p


def draw_greatsword():
    """流紋の大剣：幅の広い青銅の刃（扉の板の継ぎ目）と、背に沿う水の溝・巻き上がる鍔・長い握り・歯車の柄頭。"""
    p = Pixel()
    p.diag_band(7, 14, lambda t: [_c("q") if t % 2 else _c("f"), _c("Z"), _c("z"), _c("y")]
                + ([_c("Y")] if t <= 12 else []), dx0=-1)
    for t in (9, 12):  # 扉の板の継ぎ目
        x, y = p.axis(t)
        p.put(x + 1, y, _c("u"))
        p.put(x + 2, y, _c("Y"))
    x, y = p.axis(15)
    p.put(x - 1, y, _c("f"))
    p.put(x, y, _c("Z"))
    for u in range(-3, 4):
        x, y = p.axis(5)
        p.put(x + u, y + u, _c("Z") if abs(u) == 3 else _c("z"))
        p.put(x + u + 1, y + u, _c("Y"))
    x, y = p.axis(5)
    p.put(x, y, _c("F"))
    for t in (2, 3, 4):
        x, y = p.axis(t)
        p.put(x, y, _c("l") if t % 2 else _c("L"))
        p.put(x + 1, y, _c("L") if t % 2 else _c("l"))
    x, y = p.axis(3)
    p.put(x, y, _c("y"))
    x, y = p.axis(1)
    p.put(x, y, _c("Z"))
    p.put(x + 1, y, _c("y"))
    p.put(x, y + 1, _c("u"))
    p.put(x - 1, y, _c("u"))
    p.put(x + 1, y - 1, _c("u"))
    return p


def draw_staff():
    """流紋の杖：青銅の柄（藍の布の握り）と、先の青銅の渦に浮く水の玉（流水の結晶）。"""
    p = Pixel()
    for t in range(0, 10):
        x, y = p.axis(t)
        if t in (3, 4, 5):
            p.put(x, y, _c("n"))
            p.put(x + 1, y, _c("N"))
        else:
            p.put(x, y, _c("z") if t % 2 else _c("y"))
            p.put(x + 1, y, _c("Y") if t % 2 else _c("u"))
    head = {(10, 5): "Y", (11, 5): "y", (9, 4): "z", (10, 4): "Z",
            (12, 1): "f", (13, 1): "F", (11, 2): "q", (12, 2): "f", (13, 2): "f", (14, 2): "q",
            (11, 3): "Q", (12, 3): "q", (13, 3): "q", (14, 3): "Q", (12, 4): "Q", (13, 4): "Q",
            (10, 2): "y", (10, 1): "z", (11, 0): "Z", (12, 0): "z",
            (15, 2): "y", (15, 3): "Y", (14, 4): "Y", (14, 5): "u", (15, 4): "u"}
    for (px, py), k in head.items():
        p.put(px, py, _c(k))
    return p


def draw_bell_staff():
    """流紋の鈴杖：白い柄（金の輪）と、先の白い輪・まん中の水のしずく・下がる青銅の鈴。"""
    p = Pixel()
    for t in range(0, 9):
        x, y = p.axis(t)
        if t in (2, 6):
            p.put(x, y, _c("G"))
            p.put(x + 1, y, _c("g"))
        else:
            p.put(x, y, _c("W") if t % 2 else _c("w"))
            p.put(x + 1, y, _c("X"))
    head = {
        # 輪（白）
        (10, 1): "w", (11, 0): "W", (12, 0): "W", (13, 0): "w", (14, 1): "X", (15, 2): "X", (15, 3): "X",
        (14, 4): "X", (13, 5): "X", (9, 2): "W", (9, 3): "w", (10, 4): "w", (11, 5): "X", (12, 5): "X",
        # しずく（結晶）
        (12, 1): "F", (12, 2): "f", (13, 2): "f", (11, 2): "f", (12, 3): "q", (13, 3): "q", (11, 3): "q",
        (12, 4): "Q",
        # 鈴（青銅）
        (8, 4): "Z", (8, 5): "y", (14, 6): "Z", (15, 6): "y", (13, 7): "u",
    }
    for (px, py), k in head.items():
        p.put(px, py, _c(k))
    x, y = p.axis(9)
    p.put(x, y, _c("G"))
    return p


DRAWN = {"ryumon_sword": draw_sword, "ryumon_greatsword": draw_greatsword, "ryumon_staff": draw_staff,
         "ryumon_bell_staff": draw_bell_staff}

ARMOR_NAMES = [k for k in ART if k not in ("ryumon_bow", "ryumon_daggers", "ryumon_gauntlets")]
WEAPON_NAMES = ["ryumon_sword", "ryumon_greatsword", "ryumon_staff", "ryumon_bell_staff", "ryumon_bow",
                "ryumon_daggers", "ryumon_gauntlets"]


def pixel(name):
    p = DRAWN[name]() if name in DRAWN else _from_art(name)
    p.outline(OUTLINE)
    return p


def icon(name):
    return pixel(name).icon()


def contact_sheet(path, names, scale=8):
    from PIL import Image
    cols = 8
    rows = (len(names) + cols - 1) // cols
    cell = 16 * scale + 8
    sheet = Image.new("RGBA", (cols * cell, rows * cell), (48, 52, 60, 255))
    for k, name in enumerate(names):
        im = icon(name).image().resize((16 * scale, 16 * scale), Image.NEAREST)
        sheet.alpha_composite(im, ((k % cols) * cell + 4, (k // cols) * cell + 4))
    sheet.save(path)


