def _check(name, text):
    rows = [r for r in text.strip("\n").split("\n")]
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        raise ValueError(f"{name}：16×16 ではありません（{len(rows)}行・{[len(r) for r in rows]}）")
    return rows


def pixel(name):
    p = Pixel()
    for y, row in enumerate(_check(name, ART[name])):
        for x, ch in enumerate(row):
            if ch != ".":
                p.put(x, y, hexc(PAL[ch]))
    p.outline(OUTLINE)
    return p


def icon(name):
    return pixel(name).icon()


