def _c(k):
    return hexc(PAL[k])


def draw_sword():
    """霜銀の剣：霜銀の刃（左上のふちが明るい）とまん中の氷の稜・つららの先・雪の結晶の枝の鍔・毛皮の輪・つららの柄頭。"""
    p = Pixel()
    p.diag_band(7, 13, lambda t: [_c("Z"), _c("f") if t % 2 else _c("F"), _c("y")], dx0=-1)
    x, y = p.axis(14)
    p.put(x - 1, y, _c("Z"))
    p.put(x, y, _c("f"))
    x, y = p.axis(15)
    p.put(x - 1, y, _c("F"))
    for u in range(-3, 4):  # 鍔（ななめの棒）と、両はしの氷の枝
        x, y = p.axis(6)
        p.put(x + u, y + u, _c("z") if abs(u) < 3 else _c("f"))
        p.put(x + u + 1, y + u, _c("Y"))
    x, y = p.axis(6)
    p.put(x - 3, y - 4, _c("f"))
    p.put(x + 4, y + 3, _c("f"))
    p.put(x, y, _c("q"))
    x, y = p.axis(5)  # 毛皮の輪
    p.put(x, y, _c("X"))
    p.put(x + 1, y, _c("w"))
    for t in (3, 4):  # 握り
        x, y = p.axis(t)
        p.put(x, y, _c("l") if t % 2 else _c("L"))
        p.put(x + 1, y, _c("L") if t % 2 else _c("l"))
    x, y = p.axis(2)  # 柄頭とつらら
    p.put(x, y, _c("y"))
    p.put(x + 1, y, _c("Z"))
    x, y = p.axis(1)
    p.put(x, y, _c("f"))
    x, y = p.axis(0)
    p.put(x, y, _c("q"))
    return p


def draw_greatsword():
    """霜銀の大剣：幅の広い霜銀の刃と、まん中の氷の稜・両のふちのつららの歯・毛皮を巻いた鍔・長い握り。"""
    p = Pixel()
    p.diag_band(7, 14, lambda t: [_c("Z"), _c("z"), _c("F") if t % 2 else _c("f"), _c("y")]
                + ([_c("Y")] if t <= 12 else []), dx0=-1)
    for t in (8, 10, 12):  # つららの歯（ふちから外へ）
        x, y = p.axis(t)
        p.put(x - 2, y - 1, _c("f"))
        p.put(x + 4, y + 1, _c("f"))
    x, y = p.axis(15)
    p.put(x - 1, y, _c("F"))
    p.put(x, y, _c("Z"))
    for u in range(-3, 4):
        x, y = p.axis(5)
        p.put(x + u, y + u, _c("Z") if abs(u) == 3 else _c("z"))
        p.put(x + u + 1, y + u, _c("Y"))
    x, y = p.axis(5)
    p.put(x, y, _c("q"))
    x, y = p.axis(4)  # 毛皮の巻き
    p.put(x, y, _c("w"))
    p.put(x + 1, y, _c("X"))
    for t in (2, 3):
        x, y = p.axis(t)
        p.put(x, y, _c("l") if t % 2 else _c("L"))
        p.put(x + 1, y, _c("L") if t % 2 else _c("l"))
    x, y = p.axis(1)
    p.put(x, y, _c("Z"))
    p.put(x + 1, y, _c("y"))
    p.put(x, y + 1, _c("f"))
    return p


def draw_staff():
    """霜銀の杖：白樺の柄（黒い節）・赤い編みの握り・先の氷の八つの腕の結晶。"""
    p = Pixel()
    for t in range(0, 10):
        x, y = p.axis(t)
        if t in (3, 4, 5):
            p.put(x, y, _c("r"))
            p.put(x + 1, y, _c("R"))
        else:
            p.put(x, y, _c("i") if t % 3 else _c("d"))
            p.put(x + 1, y, _c("I"))
    x, y = p.axis(9)
    p.put(x, y, _c("z"))
    p.put(x + 1, y, _c("Y"))
    cx, cy = 12, 3  # 結晶のまん中
    for k in range(-3, 4):
        p.put(cx + k, cy, _c("f") if abs(k) < 3 else _c("F"))
        p.put(cx, cy + k, _c("f") if abs(k) < 3 else _c("F"))
    for k in (-2, -1, 1, 2):
        p.put(cx + k, cy + k, _c("q"))
        p.put(cx + k, cy - k, _c("q"))
    p.put(cx, cy, _c("F"))
    return p


def draw_bell_staff():
    """霜銀の鈴杖：白樺の柄（氷青の握り）と、先の霜銀のアーチから下がる3本のつらら。"""
    p = Pixel()
    for t in range(0, 9):
        x, y = p.axis(t)
        if t in (3, 4, 5):
            p.put(x, y, _c("b"))
            p.put(x + 1, y, _c("B"))
        else:
            p.put(x, y, _c("i") if t % 3 else _c("d"))
            p.put(x + 1, y, _c("I"))
    head = {
        # アーチ（霜銀）
        (9, 3): "y", (9, 2): "z", (10, 1): "Z", (11, 0): "Z", (12, 0): "z", (13, 0): "Z", (14, 1): "z",
        (15, 2): "y", (15, 3): "Y", (8, 4): "Y", (15, 4): "u",
        # つらら（氷）
        (11, 1): "F", (11, 2): "f", (11, 3): "q",
        (12, 1): "F", (12, 2): "f", (12, 3): "f", (12, 4): "q", (12, 5): "Q",
        (13, 1): "F", (13, 2): "f", (13, 3): "q", (13, 4): "Q",
        # てっぺんの雪の結晶
        (12, -1): "F",
    }
    for (px, py), k in head.items():
        p.put(px, py, _c(k))
    x, y = p.axis(9)
    p.put(x, y, _c("y"))
    return p


