def _check(name, text):
    rows = [r for r in text.strip("\n").split("\n")]
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        raise ValueError(f"{name}：16×16 ではありません（{len(rows)}行・{[len(r) for r in rows]}）")
    return rows


def _from_art(name):
    p = Pixel()
    for y, row in enumerate(_check(name, ART[name])):
        for x, ch in enumerate(row):
            if ch != ".":
                p.put(x, y, hexc(PAL[ch]))
    return p


def pixel(name):
    p = DRAWN[name]() if name in DRAWN else _from_art(name)
    p.outline(OUTLINE)
    return p


def icon(name):
    return pixel(name).icon()


def contact_sheet(path, names, scale=8):
    from PIL import Image
    import enhance_icons
    cols = 8
    rows = (len(names) + cols - 1) // cols
    cell = 32 * 4 + 8
    sheet = Image.new("RGBA", (cols * cell, rows * cell * 2), (48, 52, 60, 255))
    for k, name in enumerate(names):
        im16 = icon(name).image()
        im = im16.resize((128, 128), Image.NEAREST)
        sheet.alpha_composite(im, ((k % cols) * cell + 4, (k // cols) * cell * 2 + 4))
        big = enhance_icons.enhance(im16, name).resize((128, 128), Image.NEAREST)
        sheet.alpha_composite(big, ((k % cols) * cell + 4, (k // cols) * cell * 2 + cell + 4))
    sheet.save(path)


